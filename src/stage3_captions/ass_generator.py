"""
src/stage3_captions/ass_generator.py - Gerador de legendas dinâmicas em SubStation Alpha (.ass).
Estilo: Kinetic Documentário com destaque (pop/highlight) na palavra falada no momento exato.
"""

from pathlib import Path
from typing import List
import logging
from src.stage3_captions.aligner import WordTimestamp

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("ASSGenerator")


def format_ass_time(seconds: float) -> str:
    """Converte segundos para o formato H:MM:SS.cs exigido pelo formato .ass."""
    hours = int(seconds // 3600)
    minutes = int((seconds % 3600) // 60)
    secs = int(seconds % 60)
    centis = int(round((seconds - int(seconds)) * 100))
    if centis == 100:
        secs += 1
        centis = 0
    return f"{hours}:{minutes:02d}:{secs:02d}.{centis:02d}"


ASS_HEADER_TEMPLATE = """[Script Info]
; Script generated by Docu-Vibe-Studio
Title: Documentary Kinetic Captions
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: 1920
PlayResY: 1080

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,Inter,44,&H00FFFFFF,&H000000FF,&H000F1115,&H80000000,-1,0,0,0,100,100,0,0,1,3,2,2,80,80,95,1
Style: Highlight,Inter,48,&H00FFFF00,&H000000FF,&H000F1115,&H80000000,-1,0,0,0,110,110,0,0,1,4,3,2,80,80,95,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""


class ASSGenerator:
    def __init__(
        self,
        words_per_block: int = 4,
        highlight_color_hex: str = "&H00FFFF&"  # Ciano brilhante no formato BGR ASS: &H00FFFF& ou Amarelo &H0000FFFF&
    ):
        self.words_per_block = words_per_block
        self.highlight_color_hex = highlight_color_hex

    def generate_ass(self, words: List[WordTimestamp], output_path: Path) -> Path:
        """
        Agrupa palavras em blocos de 3 a 5 palavras e gera eventos com tags de override.
        Para cada palavra do bloco, gera um evento breve onde ela aparece com cor de destaque e escala aumentada.
        """
        if not words:
            logger.warning("Lista de palavras vazia. Gerando arquivo .ass vazio.")
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(ASS_HEADER_TEMPLATE, encoding="utf-8")
            return output_path

        events: List[str] = []

        # Divide as palavras em blocos
        for i in range(0, len(words), self.words_per_block):
            block = words[i : i + self.words_per_block]
            
            # Para cada palavra ativa dentro do bloco
            for current_idx, active_word in enumerate(block):
                start_str = format_ass_time(active_word.start)
                end_str = format_ass_time(active_word.end)

                # Monta o texto do bloco com a palavra atual destacada
                line_parts = []
                for idx, w in enumerate(block):
                    if idx == current_idx:
                        # Palavra ativa com destaque ciano e aumento de escala
                        line_parts.append(r"{\c" + self.highlight_color_hex + r"\fscx110\fscy110}" + w.word + r"{\r}")
                    else:
                        line_parts.append(r"{\c&H00FFFFFF\fscx100\fscy100}" + w.word)

                formatted_text = " ".join(line_parts)
                event_line = f"Dialogue: 0,{start_str},{end_str},Default,,0,0,0,,{formatted_text}"
                events.append(event_line)

        output_path.parent.mkdir(parents=True, exist_ok=True)
        content = ASS_HEADER_TEMPLATE + "\n".join(events) + "\n"
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)

        logger.info("Legenda .ass gerada com sucesso: %s (%d eventos)", output_path, len(events))
        return output_path
