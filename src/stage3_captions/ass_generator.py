"""
src/stage3_captions/ass_generator.py - Gerador de legendas cinematográficas SubStation Alpha (.ass).
Estilo: Documentário Cinematográfico Profissional (Netflix / BBC / Vox).
Sem efeito karaokê. Apresentação limpa de orações completas baseadas em pontuação
e tempo de leitura natural humano, com tipografia refinada e legibilidade absoluta.
"""

import re
from pathlib import Path
from typing import List, Dict, Any, Optional
import logging
from src.stage3_captions.aligner import WordTimestamp

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("ASSGenerator")


def format_ass_time(seconds: float) -> str:
    """Converte segundos para o formato H:MM:SS.cs exigido pelo formato .ass."""
    clamped = max(0.0, seconds)
    hours = int(clamped // 3600)
    minutes = int((clamped % 3600) // 60)
    secs = int(clamped % 60)
    centis = int(round((clamped - int(clamped)) * 100))
    if centis >= 100:
        secs += 1
        centis = 0
    return f"{hours}:{minutes:02d}:{secs:02d}.{centis:02d}"


# Template de cabeçalho ASS com tipografia de documentário (Segoe UI / Inter / Arial)
ASS_HEADER_TEMPLATE = """[Script Info]
; Script generated by Docu-Vibe-Studio v3.0 (Cinematic Documentary Engine)
Title: Cinematic Documentary Subtitles
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: 1920
PlayResY: 1080

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,Segoe UI,42,&H00FFFFFF,&H000000FF,&H0014161A,&H70000000,-1,0,0,0,100,100,0.5,0,1,2.2,1.5,2,90,90,85,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""


class ASSGenerator:
    """
    Gera legendas cinematográficas formatadas por orações sintáticas completas.
    Elimina 100% dos saltos de karaokê e divide o texto em tempos de leitura naturais.
    """

    def __init__(
        self,
        font_name: str = "Segoe UI",
        font_size: int = 42,
        max_words_per_clause: int = 8,
        min_display_sec: float = 1.3
    ):
        self.font_name = font_name
        self.font_size = font_size
        self.max_words_per_clause = max_words_per_clause
        self.min_display_sec = min_display_sec

    def generate_ass(self, words: List[WordTimestamp], output_path: Path) -> Path:
        """
        Recebe a lista de palavras alinhadas foneticamente e gera blocos de legenda
        divididos por pontuação sintática e tempo de leitura natural.
        """
        if not words:
            logger.warning("Lista de palavras vazia. Gerando arquivo .ass vazio.")
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(ASS_HEADER_TEMPLATE, encoding="utf-8")
            return output_path

        clauses = self._segment_into_syntactic_clauses(words)
        events: List[str] = []

        for idx, clause in enumerate(clauses):
            start_t = clause["start"]
            # Fim base é o final da última palavra + margem de respiração
            raw_end = clause["end"] + 0.20
            
            # Se for menor que o tempo mínimo de leitura humana, expande suavemente
            display_dur = raw_end - start_t
            if display_dur < self.min_display_sec:
                raw_end = start_t + self.min_display_sec

            # Não permite colisão com o início da próxima legenda
            if idx + 1 < len(clauses):
                next_start = clauses[idx + 1]["start"]
                if raw_end >= next_start:
                    raw_end = max(start_t + 0.3, next_start - 0.06)

            start_str = format_ass_time(start_t)
            end_str = format_ass_time(raw_end)
            text = clause["text"]

            # Balanceamento de 2 linhas se o texto for longo
            formatted_text = self._balance_lines(text)

            event_line = f"Dialogue: 0,{start_str},{end_str},Default,,0,0,0,,{formatted_text}"
            events.append(event_line)

        output_path.parent.mkdir(parents=True, exist_ok=True)
        content = ASS_HEADER_TEMPLATE + "\n".join(events) + "\n"
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)

        logger.info(
            "Legendas cinematográficas .ass geradas com sucesso: %s (%d orações sintáticas)",
            output_path.name,
            len(events)
        )
        return output_path

    def _segment_into_syntactic_clauses(self, words: List[WordTimestamp]) -> List[Dict[str, Any]]:
        """
        Agrupa palavras em orações com sentido gramatical completo.
        Corta obrigatoriamente em finais de frase (. ! ? : ;) e quebra em vírgulas
        caso o bloco já possua 4 ou mais palavras.
        """
        clauses = []
        current_words = []

        for w in words:
            current_words.append(w)
            raw_w = w.word.strip()

            # Pontuações fortes que encerram a frase
            is_sentence_end = any(raw_w.endswith(p) for p in [".", "!", "?", "...", ":", ";"])
            # Vírgula ou travessão que divide a oração
            is_comma_break = any(raw_w.endswith(p) for p in [",", "—", "-"])

            should_split = False

            if is_sentence_end:
                should_split = True
            elif is_comma_break and len(current_words) >= 4:
                should_split = True
            elif len(current_words) >= self.max_words_per_clause:
                should_split = True

            if should_split and current_words:
                clause_text = " ".join([item.word for item in current_words]).strip()
                clauses.append({
                    "start": current_words[0].start,
                    "end": current_words[-1].end,
                    "text": clause_text,
                    "word_count": len(current_words)
                })
                current_words = []

        # Adiciona remanescente se houver
        if current_words:
            clause_text = " ".join([item.word for item in current_words]).strip()
            clauses.append({
                "start": current_words[0].start,
                "end": current_words[-1].end,
                "text": clause_text,
                "word_count": len(current_words)
            })

        return clauses

    @staticmethod
    def _balance_lines(text: str) -> str:
        """
        Se a oração ultrapassar 38 caracteres, insere quebra de linha elegante (\\N)
        no espaço mais próximo do centro para criar 2 linhas equilibradas.
        """
        if len(text) <= 38:
            return text

        words = text.split()
        if len(words) < 4:
            return text

        mid = len(words) // 2
        line1 = " ".join(words[:mid])
        line2 = " ".join(words[mid:])
        return f"{line1}\\N{line2}"
